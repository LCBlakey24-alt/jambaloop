export function forkSentence(phrases, track = 'A') {
  const clean = phrases.map(text => typeof text === 'string' && text.trim() ? text.trim().replace(/[.!?,;:]+$/g,'') : '…');
  return `If the trolley takes Track ${track}, it will hit ${clean[0]}, ${clean[1]}, and ${clean[2]}.`;
}
