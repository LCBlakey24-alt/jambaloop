// Records Max and Poppy with ElevenLabs Dialogue (eleven_v3): each script is
// one natural back-and-forth take with mood tags such as [laughs] or
// [whispers]. Writes public/audio/duo/<key>.mp3 and the line timings to
// public/duo-recordings.js so captions follow the recording.
//   NODE_USE_ENV_PROXY=1 node scripts/generate-duo-voices.mjs [key ...] [--dry-run] [--redo]
// Takes that already exist are skipped (unless --redo), and nothing starts if
// the month's remaining characters can't cover the batch. The API key comes
// from XI_API_KEY or a network proxy that adds it. The free plan refuses cloud
// machines; a paid plan also carries the commercial licence.
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { duoIntros, hosts, reactionTakes, skipQuips, welcomeBack, welcomeScript } from '../public/duo-scripts.js';
import { duoRecordings } from '../public/duo-recordings.js';
import { gameGuides } from '../public/guide-scripts.js';

const api = 'https://api.elevenlabs.io/v1';
const headers = { 'xi-api-key': process.env.XI_API_KEY || 'proxy-injected', 'content-type': 'application/json' };
const args = process.argv.slice(2);
const dry = args.includes('--dry-run');
const redo = args.includes('--redo');
const scripts = { ...duoIntros, welcome: welcomeScript, 'welcome-back': welcomeBack,
  ...Object.fromEntries(skipQuips.map((lines, index) => [`skip-${index + 1}`, lines])),
  ...reactionTakes,
  ...Object.fromEntries(Object.entries(gameGuides).map(([mode, lines]) => [`guide-${mode}`, lines])) };
const wanted = args.filter(arg => !arg.startsWith('--'));
const keys = wanted.length ? wanted : Object.keys(scripts);
const folder = new URL('../public/audio/duo/', import.meta.url);
mkdirSync(folder, { recursive: true });

const recordings = { ...duoRecordings };
const jobs = keys.filter(key => scripts[key] && (redo || !recordings[key] || !existsSync(new URL(key + '.mp3', folder))));
const needed = jobs.reduce((sum, key) => sum + scripts[key].reduce((total, [, text]) => total + text.length, 0), 0);
const plan = await (await fetch(api + '/user/subscription', { headers })).json();
if (!plan.character_limit) throw new Error('ElevenLabs rejected the key: ' + JSON.stringify(plan.detail ?? plan));
const left = plan.character_limit - plan.character_count;
console.log(`${jobs.length} takes to record, ${needed} characters; ${left} of ${plan.character_limit} left this month (${plan.tier}).`);
if (needed > left) throw new Error('Not enough characters left this month. Nothing was recorded.');
if (dry) process.exit(0);

const save = () => writeFileSync(new URL('../public/duo-recordings.js', import.meta.url), `// Generated by scripts/generate-duo-voices.mjs. Each recorded exchange is one
// ElevenLabs dialogue take (public/audio/duo/<key>.mp3); the numbers are each
// line's [start, end] in seconds, so captions follow the recording.
export const duoRecordings = {
${Object.keys(recordings).sort().map(key => `  ${JSON.stringify(key)}: ${JSON.stringify(recordings[key])},`).join('\n')}
};

export const duoTake = key => \`/audio/duo/\${key}.mp3\`;
`);

for (const key of jobs) {
  const lines = scripts[key];
  const response = await fetch(`${api}/text-to-dialogue/with-timestamps?output_format=mp3_44100_96`, {
    method: 'POST', headers,
    body: JSON.stringify({ model_id: 'eleven_v3', settings: { stability: 0.5 },
      inputs: lines.map(([host, text]) => ({ text, voice_id: hosts[host].voice })) }),
  });
  if (!response.ok) throw new Error(`${key}: ${response.status} ${await response.text()}`);
  const take = await response.json();
  const segments = take.voice_segments ?? [];
  const timings = lines.map((_, index) => {
    const parts = segments.filter(segment => segment.dialogue_input_index === index);
    if (!parts.length) throw new Error(`${key}: no timing for line ${index + 1}`);
    return [Math.round(Math.min(...parts.map(part => part.start_time_seconds)) * 100) / 100,
      Math.round(Math.max(...parts.map(part => part.end_time_seconds)) * 100) / 100];
  });
  writeFileSync(new URL(key + '.mp3', folder), Buffer.from(take.audio_base64, 'base64'));
  recordings[key] = timings;
  save();
  console.log('recorded', key, `${timings.at(-1)[1]}s`);
}
const after = await (await fetch(api + '/user/subscription', { headers })).json();
console.log(`Done. ${after.character_limit - after.character_count} characters left this month.`);
