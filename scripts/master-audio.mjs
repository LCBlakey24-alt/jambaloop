// Master the recorded audio so the show sounds like one production:
//  - every voice take a touch faster (pitch kept) with dead air trimmed off the end;
//  - every file brought to one loudness per kind, so no sting or host is
//    suddenly louder than the rest.
// Files already mastered are listed in public/audio/mastered.json and skipped,
// so this is safe to run again after recording new takes. Needs ffmpeg.
//   node scripts/master-audio.mjs [--dry-run]
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, renameSync, writeFileSync } from 'node:fs';
import { duoRecordings } from '../public/duo-recordings.js';

const root = new URL('../public/audio/', import.meta.url);
const ledgerUrl = new URL('mastered.json', root);
const ledger = existsSync(ledgerUrl) ? JSON.parse(readFileSync(ledgerUrl, 'utf8')) : {};
const dry = process.argv.includes('--dry-run');
// Loudness targets (LUFS). Music sits well under speech.
const kinds = { duo: { target: -15, tempo: 1.08 }, narrator: { target: -15, tempo: 1.05 }, sfx: { target: -14 }, music: { target: -20 } };

const ffmpeg = args => execFileSync('ffmpeg', ['-hide_banner', '-nostdin', ...args], { stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' });
function probe(path, filter) {
  try { execFileSync('ffmpeg', ['-hide_banner', '-nostdin', '-i', path, '-af', filter, '-f', 'null', '-'], { stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' }); }
  catch (error) { return String(error.stderr); }
  return '';
}
const stats = path => {
  // ffmpeg writes its measurements to stderr even on success.
  const log = execFileSync('sh', ['-c', `ffmpeg -hide_banner -nostdin -i "${path}" -af ebur128=peak=true:framelog=quiet -f null - 2>&1`], { encoding: 'utf8' });
  const summary = log.slice(log.lastIndexOf('Summary:'));
  return { loudness: Number(summary.match(/I:\s+(-?[\d.]+) LUFS/)?.[1]), peak: Number(summary.match(/Peak:\s+(-?[\d.]+) dBFS/)?.[1]), duration: Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', path], { encoding: 'utf8' })) };
};

let changed = 0;
for (const [kind, { target, tempo }] of Object.entries(kinds)) {
  const folder = new URL(kind + '/', root);
  for (const file of readdirSync(folder).filter(name => name.endsWith('.mp3')).sort()) {
    const id = `${kind}/${file}`;
    if (ledger[id]) continue;
    const path = new URL(file, folder).pathname;
    const before = stats(path);
    if (!Number.isFinite(before.loudness)) { console.log(`skip ${id}: could not measure`); continue; }
    // Gain to the target; a limiter then holds any peak under -1 dBFS.
    const gain = Math.min(target - before.loudness, 36);
    // Trim silence from the end (reverse, trim the start, reverse back), keeping a short tail.
    const trim = 'areverse,silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.12,areverse';
    const filter = [tempo ? `atempo=${tempo}` : '', `volume=${gain.toFixed(2)}dB`, 'alimiter=limit=0.89:level=false', trim].filter(Boolean).join(',');
    console.log(`${id}: ${before.duration.toFixed(2)}s ${before.loudness} LUFS → gain ${gain.toFixed(1)} dB${tempo ? `, ×${tempo}` : ''}`);
    if (dry) continue;
    const temp = path + '.tmp.mp3';
    ffmpeg(['-y', '-i', path, '-af', filter, '-ar', '44100', '-codec:a', 'libmp3lame', '-b:a', '128k', temp]);
    renameSync(temp, path);
    const after = stats(path);
    ledger[id] = { tempo: tempo ?? 1, loudness: after.loudness, seconds: Number(after.duration.toFixed(2)) };
    // Captions follow the faster take.
    const key = file.replace('.mp3', '');
    if (kind === 'duo' && duoRecordings[key]) duoRecordings[key] = duoRecordings[key].map(([start, end]) => [Number((start / tempo).toFixed(2)), Number(Math.min(end / tempo, after.duration).toFixed(2))]);
    changed++;
  }
}
if (!dry && changed) {
  writeFileSync(ledgerUrl, JSON.stringify(ledger, null, 1) + '\n');
  writeFileSync(new URL('../public/duo-recordings.js', import.meta.url), `// Generated by scripts/generate-duo-voices.mjs. Each recorded exchange is one
// ElevenLabs dialogue take (public/audio/duo/<key>.mp3); the numbers are each
// line's [start, end] in seconds, so captions follow the recording.
export const duoRecordings = {
${Object.keys(duoRecordings).sort().map(key => `  ${JSON.stringify(key)}: ${JSON.stringify(duoRecordings[key])},`).join('\n')}
};

export const duoTake = key => \`/audio/duo/\${key}.mp3\`;
`);
}
console.log(`${changed} file${changed === 1 ? '' : 's'} mastered.`);
