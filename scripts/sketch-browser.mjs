import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {mkdir} from 'node:fs/promises';
const base=process.env.SITE||'http://127.0.0.1:32000';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_BIN||'/usr/bin/google-chrome',args:['--no-sandbox','--disable-dev-shm-usage']});
const tvContext=await browser.newContext({viewport:{width:1280,height:720}});
const phoneContext=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
const errors=[];
await mkdir('browser-screenshots',{recursive:true});
try{
 const api=async(path,key,data,status=200)=>{
  const res=await tvContext.request.fetch(base+'/api/rooms'+path,{method:data===undefined?'GET':'POST',headers:{...(key?{'x-game-key':key}:{})},...(data===undefined?{}:{data})});
  const body=status===204?undefined:await res.json();
  assert.equal(res.status(),status,path+' '+JSON.stringify(body));
  return body;
 };
 const created=await api('',undefined,{mode:'sketch',category:'mixed',format:'choice',count:3,seconds:0,playStyle:'individual'},201);
 const path='/'+created.code;
 const keys=[];for(let i=0;i<3;i++)keys.push((await api(path+'/join',undefined,{name:'Sketch Guest '+(i+1)},201)).key);
 const state=async(key=created.host)=>api(path,key);
 await api(path+'/advance',created.host,{phase:'lobby',index:0,game:1},204);
 const clients=await Promise.all(keys.map(key=>state(key)));
 const artistIndex=clients.findIndex(s=>s.party.drawing);
 assert.ok(artistIndex>=0);
 const artist=keys[artistIndex],answer=clients[artistIndex].party.prompt;
 assert.equal((await state()).party.prompt,undefined);
 await tvContext.addInitScript(({code,key})=>sessionStorage.setItem('quizmas-session',JSON.stringify({code,key,host:true})),{code:created.code,key:created.host});
 await phoneContext.addInitScript(({code,key})=>sessionStorage.setItem('quizmas-session',JSON.stringify({code,key,host:false})),{code:created.code,key:artist});
 const tv=await tvContext.newPage(),phone=await phoneContext.newPage();
 tv.on('pageerror',e=>errors.push('TV: '+e.message));
 phone.on('pageerror',e=>errors.push('Phone: '+e.message));
 await tv.goto(base,{waitUntil:'domcontentloaded'});
 await phone.goto(base,{waitUntil:'domcontentloaded'});
 await tv.locator('.sketch-game').waitFor();
 await phone.locator('canvas[data-sketch-interactive]').waitFor();
 assert.ok(!(await tv.locator('.sketch-game').innerText()).includes(answer),'Private prompt must not appear on the TV');
 assert.ok((await phone.locator('.sketch-secret').innerText()).toLowerCase().includes(answer.toLowerCase()));
 const rect=await phone.locator('#sketch-board').boundingBox();
 assert.ok(rect.width>200&&rect.height>100);
 await phone.mouse.move(rect.x+rect.width*.15,rect.y+rect.height*.25);
 await phone.mouse.down();
 for(let i=1;i<=8;i++)await phone.mouse.move(rect.x+rect.width*(.15+.06*i),rect.y+rect.height*(.25+.035*i),{steps:2});
 await phone.mouse.up();
 await tv.waitForFunction(()=>Number(document.querySelector('#sketch-board')?.dataset.sketchKey?.split(':')[0])>0,{timeout:15000});
 const strokes=(await state()).party.strokes;
 assert.ok(strokes.length>=1,'Drawing strokes should reach the server');
 const pixels=await tv.locator('#sketch-board').evaluate(node=>{
  const data=node.getContext('2d').getImageData(0,0,node.width,node.height).data;let count=0;
  for(let i=3;i<data.length;i+=4)if(data[i])count++;return count;
 });
 assert.ok(pixels>15,'TV must display the real drawn lines');
 await tv.screenshot({path:'browser-screenshots/sketch-drawing-tv-1280x720.png'});
 await phone.screenshot({path:'browser-screenshots/sketch-drawing-phone-390x844.png'});
 for(const key of keys)if(key!==artist)await api(path+'/party',key,{game:1,index:0,action:'guess',text:answer},204);
 const revealed=await state();assert.equal(revealed.phase,'sketch-reveal');
 assert.equal(revealed.party.answer,answer);
 assert.equal(revealed.players.reduce((n,p)=>n+p.score,0),300,'150 + 100 for guesses and 50 for the artist');
 await tv.locator('.sketch-reveal').waitFor();
 const fit=async(page,width,height,label)=>{
  const m=await page.evaluate(()=>({w:document.scrollingElement.scrollWidth,h:document.scrollingElement.scrollHeight,y:document.querySelector('#sketch-board').getBoundingClientRect().bottom}));
  assert.ok(m.w<=width+2,label+' horizontal overflow '+JSON.stringify(m));
  assert.ok(m.h<=height+2,label+' vertical overflow '+JSON.stringify(m));
  assert.ok(m.y<=height+2,label+' canvas offscreen '+JSON.stringify(m));
 };
 await fit(tv,1280,720,'TV 720p');
 await tv.screenshot({path:'browser-screenshots/sketch-reveal-tv-1280x720.png'});
 await fit(phone,390,844,'Phone 390px');
 await phone.screenshot({path:'browser-screenshots/sketch-reveal-phone-390x844.png'});
 await tv.setViewportSize({width:1920,height:1080});
 await fit(tv,1920,1080,'TV 1080p');
 await tv.screenshot({path:'browser-screenshots/sketch-reveal-tv-1920x1080.png'});
 await api(path+'/advance',created.host,{phase:'sketch-reveal',index:0,game:1},204);
 const next=await state();
 assert.equal(next.phase,'sketch-draw');
 assert.equal(next.index,1);
 assert.equal(next.party.prompt,undefined);
 assert.deepEqual(errors,[]);
 console.log('PASS: Sketch Sprint live phone drawing, TV pixels, secrets, scoring and 720p/1080p/390px layouts');
}finally{await phoneContext.close();await tvContext.close();await browser.close();}
